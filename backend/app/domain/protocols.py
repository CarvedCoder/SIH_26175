@dataclass(frozen=True)
class ArtifactRef:
    """An opaque, backend-generated address of a stored artifact.

    Keys are generated by the BACKEND (never trusted from a client) and
    are the only artifact identity business logic deals in — no raw
    filesystem paths or bucket URLs leak into application code.
    """

    key: str


@dataclass
class ArtifactMetadata:
    key: str
    size: int
    content_type: str
    checksum_sha256: str
    created_at: str = field(default_factory=utc_now)


@runtime_checkable
class ArtifactStore(Protocol):
    """Byte storage for persistent artifacts.

    Invariants:
      * keys are validated (relative, no traversal, canonical);
      * writes are atomic — a reader never observes a partial artifact;
      * the store may be local (development) or object storage
        (S3/RustFS, production) — identical behavior per the contract
        tests.
    """

    def put_bytes(
        self, key: str, data: bytes, content_type: str = "application/octet-stream"
    ) -> ArtifactRef: ...

    def get_bytes(self, key: str) -> bytes: ...

    def open(self, key: str) -> Iterator[bytes]: ...

    def exists(self, key: str) -> bool: ...

    def delete(self, key: str) -> bool: ...

    def metadata(self, key: str) -> ArtifactMetadata: ...

    def list(self, prefix: str) -> list[str]: ...
